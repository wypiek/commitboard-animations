/** Lay text out as lit pixel coordinates. Unknown characters render as '?'. */
export function textBitmap(text) {
  const pixels = [];
  let x = 0;
  for (const ch of String(text).toUpperCase()) {
    const glyph = G[ch] ?? G['?'];
    glyph.forEach((row, y) => {
      for (let i = 0; i < row.length; i++) if (row[i] === '1') pixels.push([x + i, y]);
    });
    x += glyph[0].length + 1;
  }
  return { width: Math.max(0, x - 1), pixels };
}
